// The Arduino sketch for a plan (plan.ts): tables of the pins, motors and servos the wiring record gives, and small
// non-blocking behaviours on top: obstacle avoidance when there are drive motors and a range sensor, a square when
// there is no sensor, a pose sequence for servo joints. Text only; the same plan always gives the same bytes.
import { POSE_REACH, type Plan, type ServoPlan } from "./plan.ts";

export interface Pose { name: string; angles_deg: number[]; }
export const SERIAL_BAUD = 115200;
/** fastest any servo is asked to turn (deg/s); slower when a joint's own speed limit is lower */
export const SERVO_DPS = 60;

const tenths = (d: number) => Math.round(d * 10);
const pinName = (n: number) => (n >= 14 ? `A${n - 14}` : String(n));
const pinLabel = (n: number) => (n >= 14 ? `A${n - 14}` : `D${n}`);
const hex = (n: number) => `0x${n.toString(16).toUpperCase().padStart(2, "0")}`;

/**
 * The pose sequence: home, then one joint at a time to the angles the plan allows it (POSE_REACH of the way to each
 * limit, less where a link would meet the table) and back home, so two joints never leave home together. Angles are
 * joint degrees, in the order of `servos`.
 */
export function poses(servos: ServoPlan[]): Pose[] {
  const home = servos.map((s) => s.home_deg), out: Pose[] = [{ name: "home", angles_deg: home }];
  servos.forEach((s, i) => {
    const n = out.length;
    for (const d of s.visit_deg) if (d !== null) out.push({ name: `${s.joint} to ${d} deg`, angles_deg: home.map((h, k) => (k === i ? d : h)) });
    if (out.length > n) out.push({ name: "home", angles_deg: home });
  });
  return out;
}

/** Pulse width (us) the sketch sends for a joint angle: the same integer arithmetic as `pulseFor` in the sketch. */
export function pulseFor(s: ServoPlan, angleDeg: number): number {
  const t = Math.min(tenths(s.upper_deg), Math.max(tenths(s.lower_deg), tenths(angleDeg)));
  const mid = Math.trunc((s.pulse_us[0] + s.pulse_us[1]) / 2);
  const us = mid + Math.trunc((t * (s.pulse_us[1] - s.pulse_us[0])) / (s.range_deg * 10));
  return Math.min(s.pulse_us[1], Math.max(s.pulse_us[0], us));
}

export function behaviourOf(p: Plan): string {
  const drives = p.motors.length > 0 && p.motors.every((m) => m.side), parts: string[] = [];
  if (drives) parts.push(p.range ? `drives forwards and steers away from anything the ${p.range.name} sensor sees closer than 20 cm` : "drives a square (forwards, quarter turn) with no sensor to stop it");
  if (p.servos.some((s) => s.joint)) parts.push("runs a pose sequence, one joint at a time from home, inside the joint limits");
  else if (p.servos.length) parts.push("holds its servos at their centres");
  return parts.length ? parts.join("; ") : "holds every output off (nothing in the wiring record that it can drive)";
}

export function sketch(robot: string, file: string, p: Plan): string {
  const L: string[] = [], add = (...s: string[]) => L.push(...s);
  const drives = p.motors.length > 0 && p.motors.every((m) => m.side), hasMotors = p.motors.length > 0;
  const direct = p.servos.some((s) => "pin" in s.via), onPca = p.servos.some((s) => "board" in s.via), hasServos = p.servos.length > 0;
  const seq = poses(p.servos), allPwm = p.motors.every((m) => m.pwm_is_pwm);
  const dps = Math.max(1, Math.floor(Math.min(SERVO_DPS, ...p.servos.map((s) => s.max_dps ?? SERVO_DPS))));
  const pad = (s: string, n: number) => s.padEnd(n);

  // ---------------------------------------------------------------- header
  add(`// ${file}: firmware for the robot "${robot}", generated by Text to Robot from its wiring record.`,
    "//",
    `// What it does: ${behaviourOf(p)}.`,
    `// Board:   ${p.board.name}`,
    `// FQBN:    ${p.board.fqbn}`,
    `// Serial:  ${SERIAL_BAUD} baud. It reports what it is doing; send 's' to stop everything, 's' again to go on.`,
    `// Libraries: ${libraries(p).length ? libraries(p).join(", ") : "none beyond the Arduino core"}.`,
    "//",
    "// Pin map (every line is a wire of WIRING.md that ends on the board; rewire the robot and generate again):");
  for (const q of p.pins) add(`//   ${pad(q.pin, 4)}${pad(q.mode === "unused" ? "not used" : q.mode, 9)}${q.drives}   [${q.wires.map((x) => `${x.id} ${x.net}`).join(", ")}]`);
  if (!p.pins.length) add("//   (no signal wire ends on the board)");
  if (p.pca.length) { add("//", "// Servo channels (PCA9685 outputs are wires of WIRING.md too):"); for (const s of p.servos) if ("board" in s.via) add(`//   ${p.pca[s.via.board].name} ${hex(p.pca[s.via.board].address)} channel ${pad(String(s.via.channel), 3)}${s.name}${s.joint ? ` (joint ${s.joint})` : ""}`); }
  if (p.notes.length) { add("//", "// Not driven, or to check:"); for (const n of p.notes) add(`//   - ${n}`); }
  add("//", `// First run: ${hasMotors ? "lift the wheels off the ground" : "keep clear of the joints"}${hasMotors && hasServos ? " and keep clear of the joints" : ""}, open the serial monitor, then switch the robot's power on.`);
  if (hasMotors) add("// A wheel that runs backwards during \"forward\": change its last number in MOTORS from +1 to -1 (or swap its two leads).");
  if (hasServos) add("// A joint that turns the wrong way: change its dir in JOINTS from +1 to -1. Fit each horn with the servo at its centre",
    "// (the sketch's angle 0), the joint at the zero pose of ASSEMBLY.md. Pulse ranges are the catalog's; servo batches differ,",
    "// so trim minUs / maxUs if a joint does not reach its end angles.");
  add("");
  if (onPca) add("#include <Wire.h>", "#include <Adafruit_PWMServoDriver.h>");
  if (direct) add("#include <Servo.h>");
  if (onPca || direct) add("");
  add(`const unsigned long SERIAL_BAUD = ${SERIAL_BAUD};`,
    "const unsigned long START_DELAY_MS = 2000;   // quiet time after power-on before anything moves",
    "const unsigned long REPORT_EVERY_MS = 1000;  // status line on Serial",
    "");

  // ---------------------------------------------------------------- types and tables (before the first function: the IDE writes prototypes there)
  if (hasMotors) {
    add("// ---------------------------------------------------------------- drive motors",
      "struct Motor {",
      "  const char *name;",
      `  uint8_t pwm;       // speed input of the driver${allPwm ? " (a PWM pin)" : ""}`,
      ...(allPwm ? [] : ["  bool hasPwm;       // false: this board pin has no PWM, the motor is only switched on and off"]),
      "  uint8_t in1, in2;  // direction inputs of the driver",
      "  int8_t side;       // +1 left, -1 right, 0 unknown",
      "  int8_t forward;    // +1: IN1 high drives the robot forwards; -1: IN2 high does (the right side is the left one mirrored)",
      "};",
      "const Motor MOTORS[] = {");
    for (const m of p.motors) add(`  {"${m.name}", ${pinName(m.pwm)}, ${allPwm ? "" : `${m.pwm_is_pwm}, `}${pinName(m.in1)}, ${pinName(m.in2)}, ${m.side === "left" ? "+1" : m.side === "right" ? "-1" : "0"}, ${m.forward > 0 ? "+1" : "-1"}},   // ${m.driver} channel ${m.channel}`);
    add("};",
      "const uint8_t MOTOR_COUNT = sizeof(MOTORS) / sizeof(MOTORS[0]);",
      `const int PWM_MAX = ${p.pwm_max};      // ${p.pwm_max_why}`,
      `const int CRUISE_PWM = ${Math.round(p.pwm_max * 0.8)};   // 80 % of PWM_MAX`,
      "const int TURN_PWM = PWM_MAX;   // turning on the spot drags the wheels sideways: full allowed voltage",
      "");
    if (p.standby.length) add(`const uint8_t STANDBY_PINS[] = {${p.standby.map((s) => pinName(s.pin)).join(", ")}};   // ${p.standby.map((s) => s.driver).join(", ")}: high to run`, "");
  }
  if (p.range) add("// ---------------------------------------------------------------- range sensor",
    `const uint8_t TRIG_PIN = ${pinName(p.range.trig)}, ECHO_PIN = ${pinName(p.range.echo)};   // ${p.range.name}`,
    `const unsigned int RANGE_MAX_CM = ${Math.min(200, p.range.range_cm[1])};   // the sensor reaches ${p.range.range_cm[1]} cm; listening only this far keeps one ping under ${Math.ceil((Math.min(200, p.range.range_cm[1]) * 58) / 1000)} ms`,
    "const unsigned long ECHO_TIMEOUT_US = RANGE_MAX_CM * 58UL;   // echo time / 58 = cm (datasheet)",
    "const unsigned long PING_EVERY_MS = 60;      // the datasheet asks for 60 ms between pings",
    "const unsigned int STOP_CM = 20;             // closer than this is an obstacle",
    "");
  if (drives) {
    const turn = Math.round((p.quarter_turn_s ?? 0.6) * 1000);
    add("// ---------------------------------------------------------------- driving",
      p.range ? "enum DriveState : uint8_t { DRIVE_WAIT, DRIVE_FORWARD, DRIVE_BRAKE, DRIVE_REVERSE, DRIVE_TURN };" : "enum DriveState : uint8_t { DRIVE_WAIT, DRIVE_FORWARD, DRIVE_BRAKE, DRIVE_TURN };",
      "const unsigned long BRAKE_MS = 200;",
      ...(p.range ? ["const unsigned long REVERSE_MS = 400;"] : ["const unsigned long SIDE_MS = 1500;      // one side of the square"]),
      `const unsigned long TURN_MS = ${turn};      // ${p.quarter_turn_s ? `a quarter turn at the design's ${(Math.PI / 2 / p.quarter_turn_s).toFixed(2)} rad/s on a hard floor` : "about a quarter turn"}; no encoders, so tune it on your floor`,
      "");
  }
  if (hasServos) {
    add("// ---------------------------------------------------------------- servo joints",
      "struct Joint {",
      "  const char *name;",
      ...(onPca && direct ? ["  uint8_t board;          // index into PCA, or DIRECT for a servo on a board pin"] : onPca ? ["  uint8_t board;          // index into PCA"] : []),
      `  uint8_t channel;        // ${onPca && direct ? "PCA9685 channel, or the board pin" : onPca ? "PCA9685 channel" : "board pin of the signal wire"}`,
      "  uint16_t minUs, maxUs;  // pulse at the two ends of the servo's travel (catalog)",
      "  uint16_t travel;        // that travel in degrees; the centre of it is joint angle 0",
      "  int8_t dir;             // +1: a longer pulse turns the joint positive",
      "  int16_t lower, upper, home;   // joint limits and home, tenths of a degree",
      "};",
      ...(onPca && direct ? ["const uint8_t DIRECT = 255;"] : []),
      "const Joint JOINTS[] = {");
    for (const s of p.servos) {
      const where = "board" in s.via ? `${s.via.board}, ${s.via.channel}` : `${onPca ? "DIRECT, " : ""}${pinName(s.via.pin)}`;
      add(`  {"${s.joint ?? s.name}", ${where}, ${s.pulse_us[0]}, ${s.pulse_us[1]}, ${s.range_deg}, +1, ${tenths(s.lower_deg)}, ${tenths(s.upper_deg)}, ${tenths(s.home_deg)}},   // ${s.name}: ${s.key}${s.joint ? "" : ", no joint found: held at its centre"}`);
    }
    add("};",
      "const uint8_t JOINT_COUNT = sizeof(JOINTS) / sizeof(JOINTS[0]);",
      `const uint16_t SERVO_HZ = 50;            // hobby servo frame rate`,
      `const uint16_t SERVO_SPEED_DPS = ${dps};      // the joint that moves furthest turns at this speed, the others arrive with it`,
      "const unsigned long SERVO_STEP_MS = 20;",
      "const unsigned long HOLD_MS = 800;       // pause at each pose",
      "",
      "// The pose sequence, tenths of a degree per joint in the order of JOINTS: home, then one joint at a time",
      `// up to ${Math.round(POSE_REACH * 100)} % of the way to each of its limits (less where a link would meet the table) and back home.`,
      `const int16_t POSES[][${p.servos.length}] PROGMEM = {`);
    for (const q of seq) add(`  {${q.angles_deg.map(tenths).join(", ")}},   // ${q.name}`);
    add("};", "const uint8_t POSE_COUNT = sizeof(POSES) / sizeof(POSES[0]);", "");
    if (onPca) add(`const uint32_t PCA_OSC_HZ = 25000000;    // nominal PCA9685 oscillator; clone boards are a few percent off: trim it if 50 Hz measures wrong`,
      `Adafruit_PWMServoDriver PCA[] = {${p.pca.map((b) => `Adafruit_PWMServoDriver(${hex(b.address)})`).join(", ")}};   // ${p.pca.map((b) => b.name).join(", ")}`,
      "const uint8_t PCA_COUNT = sizeof(PCA) / sizeof(PCA[0]);");
    if (direct) add("Servo servoOut[JOINT_COUNT];");
    add("int16_t jointNow[JOINT_COUNT], jointFrom[JOINT_COUNT], jointTo[JOINT_COUNT];",
      "uint16_t jointUs[JOINT_COUNT];",
      "unsigned long moveStart = 0, moveMs = 0, lastServoStep = 0, arrivedAt = 0;",
      "uint8_t pose = 0;",
      "bool moving = false;",
      "");
  }
  add("bool running = true;       // 's' on Serial toggles it", "bool started = false;", "unsigned long lastReport = 0;");
  if (drives) add("DriveState driveState = DRIVE_WAIT;", "unsigned long driveSince = 0;", "bool turnLeft = false;", "int leftPwm = 0, rightPwm = 0;");
  if (p.range) add("unsigned long lastPing = 0;", "unsigned int distanceCm = 0;   // last reading; 0: nothing within RANGE_MAX_CM");
  add("");

  // ---------------------------------------------------------------- functions
  if (hasMotors) add("// speed: -PWM_MAX..PWM_MAX, positive drives the robot forwards",
    "void setMotor(const Motor &m, int speed) {",
    "  speed = constrain(speed, -PWM_MAX, PWM_MAX);",
    "  bool ahead = (speed > 0) == (m.forward > 0);",
    "  digitalWrite(m.in1, speed != 0 && ahead ? HIGH : LOW);",
    "  digitalWrite(m.in2, speed != 0 && !ahead ? HIGH : LOW);",
    ...(allPwm ? ["  analogWrite(m.pwm, abs(speed));"] : ["  if (m.hasPwm) analogWrite(m.pwm, abs(speed));", "  else digitalWrite(m.pwm, speed != 0 ? HIGH : LOW);"]),
    "}",
    "");
  if (hasMotors && !drives) add("void stopMotors() {", "  for (uint8_t i = 0; i < MOTOR_COUNT; i++) setMotor(MOTORS[i], 0);", "}", "");
  if (drives) add("void drive(int left, int right) {",
    "  leftPwm = left;",
    "  rightPwm = right;",
    "  for (uint8_t i = 0; i < MOTOR_COUNT; i++) setMotor(MOTORS[i], MOTORS[i].side > 0 ? left : right);",
    "}",
    "");
  if (p.range) add("// One ping: 10 us on Trig, then the length of the Echo pulse. 0 when nothing answers within RANGE_MAX_CM.",
    "unsigned int readDistanceCm() {",
    "  digitalWrite(TRIG_PIN, LOW);",
    "  delayMicroseconds(2);",
    "  digitalWrite(TRIG_PIN, HIGH);",
    "  delayMicroseconds(10);",
    "  digitalWrite(TRIG_PIN, LOW);",
    "  unsigned long us = pulseIn(ECHO_PIN, HIGH, ECHO_TIMEOUT_US);",
    "  return (unsigned int)(us / 58UL);",
    "}",
    "");
  if (drives && p.range) add("void enterDrive(DriveState s) {",
    "  driveState = s;",
    "  driveSince = millis();",
    "  switch (s) {",
    "    case DRIVE_FORWARD:",
    "      drive(CRUISE_PWM, CRUISE_PWM);",
    "      Serial.println(F(\"drive: forward\"));",
    "      break;",
    "    case DRIVE_BRAKE:",
    "      drive(0, 0);",
    "      turnLeft = !turnLeft;   // turn the other way each time",
    "      Serial.print(F(\"drive: obstacle at \"));",
    "      Serial.print(distanceCm);",
    "      Serial.println(F(\" cm, stop\"));",
    "      break;",
    "    case DRIVE_REVERSE:",
    "      drive(-CRUISE_PWM, -CRUISE_PWM);",
    "      Serial.println(F(\"drive: reverse\"));",
    "      break;",
    "    case DRIVE_TURN:",
    "      if (turnLeft) drive(-TURN_PWM, TURN_PWM);",
    "      else drive(TURN_PWM, -TURN_PWM);",
    "      Serial.println(turnLeft ? F(\"drive: turn left\") : F(\"drive: turn right\"));",
    "      break;",
    "    default:",
    "      drive(0, 0);",
    "      break;",
    "  }",
    "}",
    "",
    "// Forward until something is closer than STOP_CM; then stop, back off, turn a quarter and look again.",
    "void updateDrive(unsigned long now) {",
    "  if (now - lastPing >= PING_EVERY_MS) {",
    "    lastPing = now;",
    "    distanceCm = readDistanceCm();",
    "  }",
    "  bool blocked = distanceCm > 0 && distanceCm < STOP_CM;",
    "  unsigned long in = now - driveSince;",
    "  switch (driveState) {",
    "    case DRIVE_WAIT: enterDrive(DRIVE_FORWARD); break;",
    "    case DRIVE_FORWARD: if (blocked) enterDrive(DRIVE_BRAKE); break;",
    "    case DRIVE_BRAKE: if (in >= BRAKE_MS) enterDrive(DRIVE_REVERSE); break;",
    "    case DRIVE_REVERSE: if (in >= REVERSE_MS) enterDrive(DRIVE_TURN); break;",
    "    case DRIVE_TURN: if (in >= TURN_MS) enterDrive(blocked ? DRIVE_TURN : DRIVE_FORWARD); break;",
    "  }",
    "}",
    "");
  if (drives && !p.range) add("void enterDrive(DriveState s) {",
    "  driveState = s;",
    "  driveSince = millis();",
    "  switch (s) {",
    "    case DRIVE_FORWARD:",
    "      drive(CRUISE_PWM, CRUISE_PWM);",
    "      Serial.println(F(\"drive: forward\"));",
    "      break;",
    "    case DRIVE_TURN:",
    "      drive(-TURN_PWM, TURN_PWM);",
    "      Serial.println(F(\"drive: turn left\"));",
    "      break;",
    "    default:",
    "      drive(0, 0);",
    "      Serial.println(F(\"drive: stop\"));",
    "      break;",
    "  }",
    "}",
    "",
    "// No range sensor in the wiring record: a square, by time. Nothing stops it at a wall, so give it room.",
    "void updateDrive(unsigned long now) {",
    "  unsigned long in = now - driveSince;",
    "  switch (driveState) {",
    "    case DRIVE_WAIT: enterDrive(DRIVE_FORWARD); break;",
    "    case DRIVE_FORWARD: if (in >= SIDE_MS) enterDrive(DRIVE_BRAKE); break;",
    "    case DRIVE_BRAKE: if (in >= BRAKE_MS) enterDrive(DRIVE_TURN); break;",
    "    case DRIVE_TURN: if (in >= TURN_MS) enterDrive(DRIVE_FORWARD); break;",
    "  }",
    "}",
    "");
  if (hasServos) {
    add("void printTenths(int16_t v) {",
      "  if (v < 0) Serial.print('-');",
      "  Serial.print(abs(v) / 10);",
      "  Serial.print('.');",
      "  Serial.print(abs(v) % 10);",
      "}",
      "",
      "// Pulse width for a joint angle (tenths of a degree), kept inside the joint's limits and the servo's travel.",
      "uint16_t pulseFor(const Joint &j, int16_t angle) {",
      "  angle = constrain(angle, j.lower, j.upper);",
      "  long mid = ((long)j.minUs + j.maxUs) / 2;",
      "  long us = mid + (long)j.dir * angle * (long)(j.maxUs - j.minUs) / ((long)j.travel * 10);",
      "  return (uint16_t)constrain(us, (long)j.minUs, (long)j.maxUs);",
      "}",
      "",
      "void writeJoint(uint8_t i, int16_t angle) {",
      "  jointNow[i] = angle;",
      "  uint16_t us = pulseFor(JOINTS[i], angle);",
      "  if (us == jointUs[i]) return;",
      "  jointUs[i] = us;");
    const pcaOut = ["PCA[JOINTS[i].board].setPWM(JOINTS[i].channel, 0, (uint16_t)(((uint32_t)us * 4096UL * SERVO_HZ + 500000UL) / 1000000UL));   // 12-bit count of the 20 ms frame"];
    if (onPca && direct) add("  if (JOINTS[i].board == DIRECT) servoOut[i].writeMicroseconds(us);", `  else ${pcaOut[0]}`);
    else if (onPca) add(`  ${pcaOut[0]}`);
    else add("  servoOut[i].writeMicroseconds(us);");
    add("}",
      "",
      "// Start a move to a pose: every joint arrives together, the one with furthest to go at SERVO_SPEED_DPS.",
      "void startPose(uint8_t p) {",
      "  pose = p;",
      "  int16_t far = 0;",
      "  for (uint8_t i = 0; i < JOINT_COUNT; i++) {",
      "    jointFrom[i] = jointNow[i];",
      "    jointTo[i] = constrain((int16_t)pgm_read_word(&POSES[p][i]), JOINTS[i].lower, JOINTS[i].upper);",
      "    far = max(far, (int16_t)abs(jointTo[i] - jointFrom[i]));",
      "  }",
      "  moveStart = millis();",
      "  moveMs = (unsigned long)far * 100UL / SERVO_SPEED_DPS;",
      "  moving = true;",
      "  Serial.print(F(\"pose \"));",
      "  Serial.print(p + 1);",
      "  Serial.print('/');",
      "  Serial.print(POSE_COUNT);",
      "  Serial.print(':');",
      "  for (uint8_t i = 0; i < JOINT_COUNT; i++) {",
      "    Serial.print(' ');",
      "    Serial.print(JOINTS[i].name);",
      "    Serial.print('=');",
      "    printTenths(jointTo[i]);",
      "  }",
      "  Serial.println(F(\" deg\"));",
      "}",
      "",
      "void updateJoints(unsigned long now) {",
      "  if (now - lastServoStep < SERVO_STEP_MS) return;",
      "  lastServoStep = now;",
      "  if (!moving) {",
      "    if (now - arrivedAt >= HOLD_MS && POSE_COUNT > 1) startPose((pose + 1) % POSE_COUNT);",
      "    return;",
      "  }",
      "  unsigned long t = now - moveStart;",
      "  if (t >= moveMs) {",
      "    for (uint8_t i = 0; i < JOINT_COUNT; i++) writeJoint(i, jointTo[i]);",
      "    moving = false;",
      "    arrivedAt = now;",
      "    return;",
      "  }",
      "  for (uint8_t i = 0; i < JOINT_COUNT; i++) writeJoint(i, jointFrom[i] + (int16_t)((long)(jointTo[i] - jointFrom[i]) * (long)t / (long)moveMs));",
      "}",
      "");
  }
  add("// 's' on Serial: stop everything where it is, or go on.",
    "void setRunning(bool on) {",
    "  running = on;",
    ...(drives ? ["  drive(0, 0);", "  driveState = DRIVE_WAIT;"] : hasMotors ? ["  stopMotors();"] : []),
    ...(hasServos ? ["  if (on && moving) startPose(pose);   // pick the move up from where the joints are now", "  arrivedAt = millis();"] : []),
    "  Serial.println(on ? F(\"running\") : F(\"stopped: send 's' to go on\"));",
    "}",
    "",
    "void report(unsigned long now) {",
    "  Serial.print(F(\"t=\"));",
    "  Serial.print(now / 1000);",
    "  Serial.print(F(\" s\"));",
    ...(p.range ? ["  Serial.print(F(\" dist=\"));", "  if (distanceCm) Serial.print(distanceCm);", "  else Serial.print(F(\"clear\"));", "  Serial.print(F(\" cm\"));"] : []),
    ...(drives ? ["  Serial.print(F(\" left=\"));", "  Serial.print(leftPwm);", "  Serial.print(F(\" right=\"));", "  Serial.print(rightPwm);"] : []),
    ...(hasServos ? ["  Serial.print(F(\" pose=\"));", "  Serial.print(pose + 1);", "  Serial.print(moving ? F(\" moving\") : F(\" holding\"));"] : []),
    "  Serial.println(running ? F(\"\") : F(\" stopped\"));",
    "}",
    "",
    "void setup() {",
    "  Serial.begin(SERIAL_BAUD);");
  if (p.standby.length) add("  for (uint8_t i = 0; i < sizeof(STANDBY_PINS); i++) {", "    pinMode(STANDBY_PINS[i], OUTPUT);", "    digitalWrite(STANDBY_PINS[i], HIGH);", "  }");
  if (hasMotors) add("  for (uint8_t i = 0; i < MOTOR_COUNT; i++) {",
    "    pinMode(MOTORS[i].in1, OUTPUT);",
    "    pinMode(MOTORS[i].in2, OUTPUT);",
    "    pinMode(MOTORS[i].pwm, OUTPUT);",
    "    setMotor(MOTORS[i], 0);",
    "  }");
  if (p.range) add("  pinMode(TRIG_PIN, OUTPUT);", "  digitalWrite(TRIG_PIN, LOW);", "  pinMode(ECHO_PIN, INPUT);");
  if (onPca) add("  for (uint8_t b = 0; b < PCA_COUNT; b++) {",
    "    PCA[b].begin();",
    "    PCA[b].setOscillatorFrequency(PCA_OSC_HZ);",
    "    PCA[b].setPWMFreq(SERVO_HZ);",
    "  }");
  if (hasServos) add("  // every servo goes to its home angle at once: a hobby servo has no feedback, so the first pulse is a jump",
    "  for (uint8_t i = 0; i < JOINT_COUNT; i++) {",
    ...(direct ? [`    ${onPca ? "if (JOINTS[i].board == DIRECT) " : ""}servoOut[i].attach(JOINTS[i].channel, JOINTS[i].minUs, JOINTS[i].maxUs);`] : []),
    "    jointTo[i] = JOINTS[i].home;",
    "    writeJoint(i, JOINTS[i].home);",
    "  }");
  add(`  Serial.println(F("${robot}: ${file}"));`);
  if (hasMotors) add(`  Serial.println(F("${p.motors.length} motor${p.motors.length === 1 ? "" : "s"}, PWM limit ${p.pwm_max}/255"));`);
  if (hasServos) add(`  Serial.println(F("${p.servos.length} servo${p.servos.length === 1 ? "" : "s"}${p.pca.length ? ` on ${p.pca.map((b) => `${b.name} ${hex(b.address)}`).join(", ")}` : ""}, ${seq.length} poses"));`);
  if (p.range) add(`  Serial.println(F("range sensor ${p.range.name}: Trig ${pinLabel(p.range.trig)}, Echo ${pinLabel(p.range.echo)}"));`);
  add("  Serial.println(F(\"send 's' to stop or go on\"));",
    "}",
    "",
    "void loop() {",
    "  unsigned long now = millis();",
    "  while (Serial.available()) {",
    "    if (Serial.read() == 's') setRunning(!running);",
    "  }",
    "  if (!started && now >= START_DELAY_MS) {",
    "    started = true;",
    ...(hasServos ? ["    arrivedAt = now;"] : []),
    "    Serial.println(F(\"start\"));",
    "  }",
    "  if (started && running) {",
    ...(drives ? ["    updateDrive(now);"] : []),
    ...(hasServos ? ["    updateJoints(now);"] : []),
    ...(!drives && !hasServos ? ["    // nothing to run: see the notes at the top"] : []),
    "  }",
    "  if (now - lastReport >= REPORT_EVERY_MS) {",
    "    lastReport = now;",
    "    report(now);",
    "  }",
    "}",
    "");
  return L.join("\n");
}

/** Libraries the sketch includes, by their Library Manager names (Wire comes with the board core). */
export function libraries(p: Plan): string[] {
  const out: string[] = [];
  if (p.servos.some((s) => "pin" in s.via)) out.push("Servo");
  if (p.servos.some((s) => "board" in s.via)) out.push("Wire", "Adafruit PWM Servo Driver Library");
  return out;
}
