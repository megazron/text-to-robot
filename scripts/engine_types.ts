// Write the engine API's type declarations as one file (engine/v1/engine.d.ts on the website), from the sources:
// TypeScript emits declarations for the client, the edit and snap modules and the robot specification types; their
// imports between each other are dropped because everything ends up in the same module.
//   node scripts/engine_types.ts <out.d.ts>
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";

const out = process.argv[2];
if (!out) throw new Error("usage: node scripts/engine_types.ts <out.d.ts>");
const dir = mkdtempSync(join(tmpdir(), "ttr-dts-"));
try {
  execFileSync("npx", ["tsc", "--ignoreConfig", "apps/web/src/engine/client.ts", "packages/robot-schema/src/types.ts", "--declaration", "--emitDeclarationOnly", "--outDir", dir,
    "--module", "nodenext", "--moduleResolution", "nodenext", "--target", "es2022", "--allowImportingTsExtensions", "--rewriteRelativeImportExtensions", "--skipLibCheck", "--lib", "es2022,dom", "--types", "node"], { stdio: "inherit" });
  const files: string[] = [];
  const walk = (d: string) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (f.endsWith(".d.ts")) files.push(p); } };
  walk(dir);
  const order = ["types.d.ts", "edit.d.ts", "snap.d.ts", "client.d.ts"];
  const pick = (n: string) => { const f = files.find((x) => x.endsWith(`/${n}`)); if (!f) throw new Error(`tsc wrote no ${n}`); return f; };
  const body = order.map((n) => readFileSync(pick(n), "utf8")
    .split("\n").filter((l) => !/^import /.test(l) && !/^export (type )?\{[^}]*\}( from .*)?;?$/.test(l) && !/^export \{\};?$/.test(l)).join("\n")).join("\n");
  writeFileSync(out, `// Text to Robot engine API, version 1: type declarations (generated by scripts/engine_types.ts from the sources).\n${body}\n`);
} finally { rmSync(dir, { recursive: true, force: true }); }
