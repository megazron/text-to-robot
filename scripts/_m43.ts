import { designMark43Wearable } from "@ttr/design";
import { generateUrdf } from "@ttr/urdf-generator";
import { collectMeshFiles } from "@ttr/robot-generator";
import { mkdirSync, writeFileSync } from "node:fs";
const tier = (process.argv[2] ?? "helmet") as any;
const t0 = Date.now(), s = designMark43Wearable({ tier }), d = (s.metadata as any).design;
console.log(d.summary, ((Date.now() - t0) / 1000).toFixed(1) + " s");
for (const c of d.checks) if (!c.pass || process.env.ALL) console.log("  ", c.pass ? "ok" : "FAIL", c.name, "-", c.detail);
const dir = `/tmp/claude-1000/m43_${tier}`; mkdirSync(`${dir}/meshes`, { recursive: true });
writeFileSync(`${dir}/robot.urdf`, generateUrdf(s));
for (const [f, b] of Object.entries(collectMeshFiles(s))) writeFileSync(`${dir}/meshes/${f}`, b as Uint8Array);
